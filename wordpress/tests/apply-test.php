$out['draft_ok'] = $r2[0]['ok'];
$out['draft_status'] = get_post_status($r2[0]['post_id']);
$out['draft_slug'] = get_post_field('post_name', $r2[0]['post_id']);
$out['draft_url'] = $r2[0]['url'];
onpage_dev_undo($set2['id']);
$out['draft_after_undo'] = get_post_status($r2[0]['post_id']);
$set3 = array('id' => '00000000-0000-4000-8000-000000000003', 'url' => get_permalink($id), 'changes' => array(array('field' => 'post_content', 'value' => '<p>Third.</p>')));
