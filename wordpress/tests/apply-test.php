$out['patch_ok'] = $r[0]['ok'];
$out['patched'] = get_post_field('post_content', $id, 'raw');
$out['undo_all'] = onpage_dev_undo($set['id']);
$out['undone'] = get_post_field('post_content', $id, 'raw');
$set2 = array('id' => '00000000-0000-4000-8000-000000000002', 'url' => home_url('/'), 'changes' => array(array('field' => 'new_post', 'value' => array('title' => 'Raised bed soil', 'content' => '<p>Hello</p>', 'slug' => 'raised-bed-soil', 'type' => 'post'))));
