<?php
require_once '/wordpress/wp-load.php';
wp_set_current_user(1);
$out = array();
$id = wp_insert_post(array('post_title' => 'Compost', 'post_content' => '<p>Old one.</p><p>Old two.</p>', 'post_status' => 'publish'));
$set = array('id' => '00000000-0000-4000-8000-000000000001', 'url' => get_permalink($id), 'changes' => array(array('field' => 'post_content', 'value' => '<p>Old one.</p><p>New <script>alert(1)</script>three.</p>')));
