$out['view_ins'] = false !== strpos($view, '<ins>Add this.</ins>');
$out['view_escaped'] = false === strpos(onpage_dev_content_new(array('url' => get_permalink($view_id)), array('field' => 'post_content', 'value' => '<p>x</p><img src=x onerror=alert(1)>')), 'onerror');
$out['now_words'] = onpage_dev_content_now(array('url' => get_permalink($view_id)), 'post_content');
file_put_contents('/out/result.json', wp_json_encode($out));
